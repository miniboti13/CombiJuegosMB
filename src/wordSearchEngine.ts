const ALPHABET = 'ABCDEFGHIJKLMNÑOPQRSTUVWXYZ';

const DIRECTIONS = [
  { r: 0, c: 1 },
  { r: 0, c: -1 },
  { r: 1, c: 0 },
  { r: -1, c: 0 },
  { r: 1, c: 1 },
  { r: -1, c: -1 },
  { r: 1, c: -1 },
  { r: -1, c: 1 },
];

export interface GeneratedBoard {
  board: string[][];
  placedWords: string[];
}

export function generateBoard(
  wordCount: number = 6,
  size: number = 10,
  wordBank: string[] = LARGE_WORD_BANK
): GeneratedBoard {
  const shuffledBank = [...wordBank].sort(() => 0.5 - Math.random());
  const selectedWords = shuffledBank.slice(0, wordCount).map(w => w.toUpperCase());

  let board: string[][] = Array(size).fill(null).map(() => Array(size).fill(''));
  const placedWords: string[] = [];

  selectedWords.forEach(word => {
    let placed = false;
    let attempts = 0;

    while (!placed && attempts < 150) {
      attempts++;
      const dir = DIRECTIONS[Math.floor(Math.random() * DIRECTIONS.length)];
      const startRow = Math.floor(Math.random() * size);
      const startCol = Math.floor(Math.random() * size);

      const endRow = startRow + dir.r * (word.length - 1);
      const endCol = startCol + dir.c * (word.length - 1);

      if (endRow >= 0 && endRow < size && endCol >= 0 && endCol < size) {
        let canPlace = true;
        for (let i = 0; i < word.length; i++) {
          const r = startRow + dir.r * i;
          const c = startCol + dir.c * i;
          if (board[r][c] !== '' && board[r][c] !== word[i]) {
            canPlace = false;
            break;
          }
        }

        if (canPlace) {
          for (let i = 0; i < word.length; i++) {
            const r = startRow + dir.r * i;
            const c = startCol + dir.c * i;
            board[r][c] = word[i];
          }
          placed = true;
          placedWords.push(word);
        }
      }
    }
  });

  for (let r = 0; r < size; r++) {
    for (let c = 0; c < size; c++) {
      if (board[r][c] === '') {
        const randomChar = ALPHABET[Math.floor(Math.random() * ALPHABET.length)];
        board[r][c] = randomChar;
      }
    }
  }

  return { board, placedWords };
}